import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { chromium, expect } from '@playwright/test';
import { randomBytes } from 'node:crypto';
import fs, { writeFileSync } from 'node:fs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const stamp = Date.now();
const password = `Test${randomBytes(12).toString('hex')}1`;
const errors = [];
const records = {};
const liveSteps = [];

const origin = 'http://127.0.0.1:5173';
const backendDir = resolve(process.env.JOB_BOARD_BACKEND_DIR || '../job-board-backend');
const liveDatabase = process.env.AI2_TEST_DB || 'job_board_db';
if (!/^[a-z][a-z0-9_]*$/.test(liveDatabase)) throw new Error('Invalid local test database name');
// Explicit test command: creates example.test accounts, a company, a job and an application.
fs.mkdirSync('logs', { recursive: true });
async function account(role) {
  const context = await browser.newContext({ baseURL: origin });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/register');
  await page.getByLabel('Họ và tên').fill(`Kiểm thử ${role}`);
  await page.getByLabel('Email', { exact: true }).fill(`frontend.${role}.${stamp}@example.test`);
  await page.getByLabel('Vai trò').selectOption(role);
  await page.getByLabel('Mật khẩu', { exact: true }).fill(password);
  await page.getByLabel('Nhập lại mật khẩu').fill(password);
  await page.getByRole('button', { name: 'Đăng ký', exact: true }).click();
  await expect(page).not.toHaveURL(/register/);
  return page;
}
try {
  const employer = await account('employer');
  await employer.goto('/employer/company');
  await employer.getByLabel('Tên công ty').fill(`Kiểm thử frontend ${stamp}`);
  await employer.getByLabel('Giới thiệu công ty').fill('Dữ liệu kiểm thử tích hợp frontend với backend AI2.');
  await employer.getByLabel('Tỉnh / thành phố').fill('Hà Nội');
  const companySaved = employer.waitForResponse(r => r.url().endsWith('/api/companies') && r.request().method() === 'POST');
  await employer.getByRole('button', { name: 'Tạo công ty', exact: true }).click();
  const companyResponse = await companySaved;
  if (!companyResponse.ok()) throw new Error(`Create company HTTP ${companyResponse.status()}`);
  records.companyId = (await companyResponse.json()).id;
  await employer.goto('/employer/jobs/new');
  await employer.getByLabel('Tiêu đề tuyển dụng').fill(`Kiểm thử React Developer ${stamp}`);
  await employer.getByLabel('Mô tả công việc').fill('Build React and TypeScript applications with REST APIs. Frontend developer with React, TypeScript, HTML and CSS skills.');
  await employer.getByLabel('Cấp bậc', { exact: true }).selectOption('junior');
  await employer.getByLabel('Tỉnh / thành phố').fill('Hà Nội');
  await employer.getByRole('checkbox', { name: 'React', exact: true }).check();
  const jobSaved = employer.waitForResponse(r => r.url().endsWith('/api/jobs') && r.request().method() === 'POST');
  await employer.getByRole('button', { name: 'Đăng tin tuyển dụng →' }).click();
  const jobResponse = await jobSaved;
  if (!jobResponse.ok()) throw new Error(`Create job HTTP ${jobResponse.status()}`);
  records.jobId = (await jobResponse.json()).id;
  await expect(employer.getByRole('heading', { name: 'Tin tuyển dụng đã sẵn sàng.' })).toBeVisible();
  await employer.goto('/employer/jobs');
  await expect(employer.getByRole('cell', { name: new RegExp(`Kiểm thử React Developer ${stamp}`) })).toBeVisible();
  console.log('PASS real employer registration, company, skills and posting');
  // Current JobsService does not enqueue embeddings; initialize this test job only.
  execFileSync(process.execPath, ['--env-file=.env', '-e', `
    const {NestFactory}=require('./node_modules/@nestjs/core');
    const {AppModule}=require('./dist/src/app.module');
    const {AiJobsService}=require('./dist/src/modules/ai/jobs/ai-jobs.service');
    (async()=>{const app=await NestFactory.createApplicationContext(AppModule,{logger:false}); try{await app.get(AiJobsService).embedJobs([Number(process.argv[1])]);} finally{await app.close();}})().catch(()=>process.exit(1));
  `, String(records.jobId)], { cwd:backendDir, env:{...process.env, DB_NAME:liveDatabase, AI_ENABLED:'true', RABBITMQ_URL:'amqp://127.0.0.1:5675', REDIS_HOST:'127.0.0.1', REDIS_PORT:'6382'}, stdio:'ignore', timeout:90000 });
  liveSteps.push('initialized embedding for new job using real backend service; create currently does not enqueue');
  const candidate = await account('candidate');
  await candidate.goto('/me');
  await candidate.getByLabel('Họ và tên').fill('Kiểm thử ứng viên cập nhật');
  await candidate.getByRole('button', { name: 'Lưu thay đổi' }).click();
  await expect(candidate.getByText('Đã cập nhật hồ sơ thành công.')).toBeVisible();
  await candidate.goto('/me/resumes');
  await candidate.getByLabel('Chọn tệp CV').setInputFiles({ name: 'frontend-integration.pdf', mimeType: 'application/pdf', buffer: await (async () => {
    const doc = await candidate.context().newPage();
    await doc.setContent('<h1>Frontend React Developer</h1><p>Skills: React, TypeScript, HTML, CSS, JavaScript, REST API, Git, SQL, Docker.</p><p>Junior software developer in Ha Noi with 2 years experience building React applications and integrating REST APIs. Developed reusable TypeScript components, unit tests and accessible responsive interfaces.</p><p>Desired position: React Frontend Developer. Projects: job board application with React, TypeScript, HTML, CSS, Git and REST API integration.</p>');
    const bytes = await doc.pdf(); await doc.close(); return bytes;
  })() });
  await candidate.getByRole('button', { name: 'Tải lên CV', exact: true }).click();
  await expect(candidate.getByText('CV đã được tải lên thành công.')).toBeVisible();
  liveSteps.push('register employer/candidate, company, job, upload PDF');
  await candidate.locator('article').first().getByRole('button', { name: 'Phân tích bằng AI', exact: true }).click();
  await expect(candidate.getByRole('region', { name: 'Phân tích CV bằng AI' }).locator('.ai-skills').first()).toContainText('React', { timeout: 65000 });
  await candidate.screenshot({ path: 'logs/ai2-live-resume-analysis.png', fullPage: true });
  liveSteps.push('CV automatically parsed through RabbitMQ without refresh');
  await candidate.goto('/me/recommended-jobs');
  await candidate.getByRole('button', { name: 'Tìm việc phù hợp', exact: true }).click();
  const card = candidate.locator('.ai-match-card').filter({ hasText: 'Kiểm thử React Developer ' + stamp });
  await expect(card).toContainText('React', { timeout: 65000 });
  await candidate.screenshot({ path: 'logs/ai2-live-recommendations.png', fullPage: true });
  await card.getByRole('button', { name: 'Ứng tuyển ngay', exact: true }).click();
  liveSteps.push('recommendation contains new job and opens apply dialog');
  await candidate.getByLabel('Thư giới thiệu').fill('CV kiểm thử tích hợp frontend.');
  await candidate.getByRole('button', { name: 'Gửi hồ sơ' }).click();
  await expect(candidate).toHaveURL(/\/me\/applications\/\d+$/);
  records.applicationId = Number(new URL(candidate.url()).pathname.split('/').pop());
  await expect(candidate.getByRole('heading', { name: 'Chi tiết đơn ứng tuyển' })).toBeVisible();
  console.log('PASS real candidate registration, profile, CV upload and application');
  liveSteps.push('application submitted from recommendation');
  await candidate.goto('/me/applications');
  await expect(candidate.getByText('Kiểm thử React Developer ' + stamp, { exact: true })).toBeVisible();
  await candidate.goto('/me/applications/' + records.applicationId);
  await employer.goto('/employer/jobs/' + records.jobId + '/applications');
  await expect(employer.locator('tbody')).toContainText('Kiểm thử ứng viên cập nhật');
  await employer.goto('/employer/applications/' + records.applicationId + '?jobId=' + records.jobId);
  await expect(employer.getByRole('heading', { name: 'Kiểm thử ứng viên cập nhật', exact: true })).toBeVisible();
  const aiPanel = employer.getByRole('region', { name: 'Đánh giá AI', exact: true });
  await expect(aiPanel.getByRole('progressbar')).toBeVisible({ timeout: 65000 });
  liveSteps.push('employer sees real candidate name and scored AI evaluation');
  await employer.screenshot({ path: 'logs/ai2-live-employer-ai.png', fullPage: true });
  await expect(employer.getByLabel('Trạng thái mới')).toBeEnabled();
  await expect(employer.getByRole('button', { name: 'Tải CV', exact: true })).toBeEnabled();
  await employer.getByLabel('Trạng thái mới').selectOption('interview');
  await employer.getByLabel('Ghi chú cho ứng viên').fill('Kiểm thử: mời phỏng vấn qua hệ thống.');
  await employer.getByRole('button', { name: 'Cập nhật trạng thái', exact: true }).click();
  await employer.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(employer.getByText('Đã cập nhật trạng thái và lịch sử hồ sơ.')).toBeVisible();
  await candidate.reload();
  await expect(candidate.getByText('Kiểm thử: mời phỏng vấn qua hệ thống.')).toBeVisible();
  await employer.screenshot({ path: 'logs/ai2-live-employer-verified.png', fullPage: true });
  await candidate.screenshot({ path: 'logs/ai2-live-candidate-verified.png', fullPage: true });
  console.log('PASS real employer CV access, interview update and candidate history');
  if (errors.length) throw new Error(errors.join('\n'));
  const guest = await browser.newPage();
  const detailRequests = [];
  guest.on('request', r => { if (/\/api\/jobs\/\d+(?:\?|$)/.test(r.url())) detailRequests.push(r.url()); });
  await guest.goto(origin + '/jobs?mode=like');
  await guest.getByLabel('Từ khóa tìm việc').fill('Kiểm thử React Developer ' + stamp);
  await guest.getByRole('button', { name: 'Tìm việc', exact: true }).click();
  await expect(guest.locator('.public-job-name')).toContainText(['Kiểm thử React Developer ' + stamp]);
  if (detailRequests.length) throw new Error('Rich search unexpectedly fetched detail');
  await guest.screenshot({ path: 'logs/ai2-live-search.png', fullPage: true });
  liveSteps.push('real rich search mode=like without detail requests');
  console.log('PASS no browser page errors and rich search');
} finally {
  writeFileSync('logs/ai2-live-result.json', JSON.stringify({ stamp, records, liveSteps, errors }, null, 2));
  await browser.close();
}
